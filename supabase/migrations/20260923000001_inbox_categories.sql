-- Separate messages from notifications in the console inbox (fix-list 71).
--
-- WHY. `inbox_messages` was built for the contact and advertising enquiry forms
-- — things a person wrote, expecting a reply. Over time eight machine-generated
-- event notices were inserted into it as well (signup started, payment taken,
-- comp expired, grace ended, advert run ending soon...), because it was the only
-- console-facing feed that existed. The result is one list mixing "a customer
-- asked you a question" with "a background job did a thing", and the reply form
-- is offered on both: `jobs.ts` inserts its advert-expiry notice with
-- `email: ''`, so replying to that row sends to nobody.
--
-- WHAT. A `category` column splits the two, `kind` is widened to name the events
-- properly instead of overloading 'membership', and `member_id` + `payload` let
-- a notification link to the thing it is about — which is the whole point of a
-- notification, and what the member-side `notifications` table has always had.
--
-- The backfill deliberately errs towards 'message'. An unrecognised notice
-- appearing in the inbox is the status quo and costs a second to dismiss; a real
-- enquiry silently reclassified as a notification is a customer who never got an
-- answer. So the column default does the safe thing and only the eight known
-- machine-generated message bodies are promoted to 'notification'. Note that
-- `email` is NOT a usable discriminator — membership.ts and jobs.ts both write
-- the member's real contact address on rows that are notifications.

alter table inbox_messages
  add column if not exists category text not null default 'message',
  add column if not exists member_id uuid references members(id) on delete set null,
  add column if not exists payload jsonb not null default '{}'::jsonb;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'inbox_messages_category_check'
  ) then
    alter table inbox_messages add constraint inbox_messages_category_check
      check (category in ('message', 'notification'));
  end if;
end $$;

-- 'contact' | 'advertising' | 'membership' were the only kinds. The first two
-- stay as they are (they name the form a message came from); the event kinds are
-- new and are what the notifications half of the feed filters on.
alter table inbox_messages drop constraint if exists inbox_messages_kind_check;
alter table inbox_messages add constraint inbox_messages_kind_check
  check (kind in (
    -- messages: a person wrote this
    'contact', 'advertising', 'membership',
    -- notifications: something happened
    'signup_started', 'payment_taken', 'page_submitted', 'payment_failed',
    'subscription_ended', 'comp_expired', 'membership_lapsed', 'advert_ending',
    'story_submitted', 'video_submitted', 'event_submitted', 'machine_submitted',
    'advert_submitted', 'artwork_submitted'
  ));

-- Promote the known machine-written rows. Matched on the message text because
-- these strings are generated by code and are therefore exact; anything that
-- does not match keeps the safe 'message' default.
update inbox_messages set category = 'notification', kind = 'signup_started'
  where kind = 'membership' and message like 'Started the join flow:%';
update inbox_messages set category = 'notification', kind = 'payment_taken'
  where kind = 'membership' and (message like 'Paid £40/month by card%' or message like 'Redeemed promo code %');
update inbox_messages set category = 'notification', kind = 'page_submitted'
  where kind = 'membership' and message like 'Submitted their draft company page for review%';
update inbox_messages set category = 'notification', kind = 'payment_failed'
  where kind = 'membership' and message like 'Card payment failed%';
update inbox_messages set category = 'notification', kind = 'subscription_ended'
  where kind = 'membership' and message like 'Subscription cancelled and membership ended%';
update inbox_messages set category = 'notification', kind = 'comp_expired'
  where kind = 'membership' and message like 'Promo comp expired%';
update inbox_messages set category = 'notification', kind = 'membership_lapsed'
  where kind = 'membership' and message like 'Grace period ended%';
update inbox_messages set category = 'notification', kind = 'advert_ending'
  where kind = 'advertising' and message like 'Advert run %ends on%';

-- The feed pages on (category, read) and the header bell counts unread.
create index if not exists inbox_messages_category_read_idx
  on inbox_messages (category, read, created_at desc);

-- Replies: stored, not fire-and-forget (fix-list 71b, GAPS B3.4 first half).
--
-- `replyToInboxMessage` sent an email and kept nothing, so there was no way to
-- tell an answered enquiry from an unanswered one, and a provider rejection
-- destroyed whatever had just been typed. The row is now written before the send
-- and stamped after it, so a failed send keeps the text and shows why.
--
-- A table rather than a column on inbox_messages: a thread can have more than one
-- reply, and what was actually said is the part worth keeping.
alter table inbox_messages add column if not exists replied_at timestamptz;

create table if not exists inbox_replies (
  id uuid primary key default gen_random_uuid(),
  message_id uuid not null references inbox_messages(id) on delete cascade,
  subject text not null,
  body text not null,
  sent_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  delivery_error text
);

create index if not exists inbox_replies_message_idx on inbox_replies (message_id, created_at);

alter table inbox_replies enable row level security;
-- no policies: console-managed, written and read via the service role only.
